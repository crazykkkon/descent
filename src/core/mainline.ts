/** 主线每层的选图（第 1、2 层按种子随机，其余只有一张图） */
export function pickMainline(seed: number, avoid?: FloorChoice[]): FloorChoice[] {
    return pickChoices(seed, MAINLINE, avoid);
}

export function buildMainline(choices: FloorChoice[]): FloorDef[] {
    return choices.map((c, i) => buildFloor(MAINLINE[i], c));
}
